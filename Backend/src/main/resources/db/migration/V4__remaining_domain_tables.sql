CREATE TABLE pin_evaluations (
                                 id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 pin_id     BIGINT       NOT NULL,
                                 member_id  BIGINT       NOT NULL,
                                 evaluation VARCHAR(255) NOT NULL,

                                 CONSTRAINT uk_pin_evaluations_pin_id_member_id
                                     UNIQUE (pin_id, member_id),

                                 CONSTRAINT fk_pin_evaluations_pin
                                     FOREIGN KEY (pin_id) REFERENCES pins (id),

                                 CONSTRAINT fk_pin_evaluations_member
                                     FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_pin_evaluations_pin_id
    ON pin_evaluations (pin_id);

CREATE INDEX idx_pin_evaluations_member_id
    ON pin_evaluations (member_id);


CREATE TABLE pin_tags (
                          id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          pin_id BIGINT      NOT NULL,
                          tag    VARCHAR(30) NOT NULL,

                          CONSTRAINT uk_pin_tags_pin_id_tag
                              UNIQUE (pin_id, tag),

                          CONSTRAINT fk_pin_tags_pin
                              FOREIGN KEY (pin_id) REFERENCES pins (id)
);

CREATE INDEX idx_pin_tags_pin_id
    ON pin_tags (pin_id);


CREATE TABLE pin_unlocks (
                             id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             pin_id          BIGINT NOT NULL,
                             member_id       BIGINT NOT NULL,
                             idempotency_key UUID   NOT NULL,

                             CONSTRAINT uk_pin_unlocks_pin_id_member_id
                                 UNIQUE (pin_id, member_id),

                             CONSTRAINT uk_pin_unlocks_idempotency_key
                                 UNIQUE (idempotency_key),

                             CONSTRAINT fk_pin_unlocks_pin
                                 FOREIGN KEY (pin_id) REFERENCES pins (id),

                             CONSTRAINT fk_pin_unlocks_member
                                 FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_pin_unlocks_pin_id
    ON pin_unlocks (pin_id);

CREATE INDEX idx_pin_unlocks_member_id
    ON pin_unlocks (member_id);


CREATE TABLE search_histories (
                                  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  member_id   BIGINT       NOT NULL,
                                  place_id    BIGINT,
                                  search_type VARCHAR(255) NOT NULL,
                                  keyword     VARCHAR(200),
                                  created_at  TIMESTAMP(6) WITH TIME ZONE,
                                  updated_at  TIMESTAMP(6) WITH TIME ZONE,

                                  CONSTRAINT fk_search_histories_member
                                      FOREIGN KEY (member_id) REFERENCES members (id),

                                  CONSTRAINT fk_search_histories_place
                                      FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE INDEX idx_search_histories_member_id
    ON search_histories (member_id);

CREATE INDEX idx_search_histories_place_id
    ON search_histories (place_id);


CREATE TABLE chat_rooms (
                            id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            pin_id          BIGINT       NOT NULL,
                            requester_id    BIGINT       NOT NULL,
                            status          VARCHAR(255) NOT NULL,
                            idempotency_key UUID         NOT NULL,
                            created_at      TIMESTAMP(6) WITH TIME ZONE,
                            updated_at      TIMESTAMP(6) WITH TIME ZONE,

                            CONSTRAINT uk_chat_rooms_pin_id_requester_id
                                UNIQUE (pin_id, requester_id),

                            CONSTRAINT uk_chat_rooms_idempotency_key
                                UNIQUE (idempotency_key),

                            CONSTRAINT fk_chat_rooms_pin
                                FOREIGN KEY (pin_id) REFERENCES pins (id),

                            CONSTRAINT fk_chat_rooms_requester
                                FOREIGN KEY (requester_id) REFERENCES members (id)
);

CREATE INDEX idx_chat_rooms_pin_id
    ON chat_rooms (pin_id);

CREATE INDEX idx_chat_rooms_requester_id
    ON chat_rooms (requester_id);


CREATE TABLE chat_room_members (
                                   id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   chat_room_id         BIGINT NOT NULL,
                                   member_id            BIGINT NOT NULL,
                                   last_read_message_id BIGINT,
                                   created_at           TIMESTAMP(6) WITH TIME ZONE,
                                   updated_at           TIMESTAMP(6) WITH TIME ZONE,

                                   CONSTRAINT uk_chat_room_members_chat_room_id_member_id
                                       UNIQUE (chat_room_id, member_id),

                                   CONSTRAINT fk_chat_room_members_chat_room
                                       FOREIGN KEY (chat_room_id) REFERENCES chat_rooms (id),

                                   CONSTRAINT fk_chat_room_members_member
                                       FOREIGN KEY (member_id) REFERENCES members (id)
);

CREATE INDEX idx_chat_room_members_chat_room_id
    ON chat_room_members (chat_room_id);

CREATE INDEX idx_chat_room_members_member_id
    ON chat_room_members (member_id);


CREATE TABLE chat_messages (
                               id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               chat_room_id      BIGINT      NOT NULL,
                               sender_id         BIGINT      NOT NULL,
                               client_message_id UUID        NOT NULL,
                               type              VARCHAR(30) NOT NULL,
                               content           TEXT        NOT NULL,
                               masked_content    TEXT,
                               created_at        TIMESTAMP(6) WITH TIME ZONE,
                               updated_at        TIMESTAMP(6) WITH TIME ZONE,

                               CONSTRAINT uk_chat_messages_sender_id_client_message_id
                                   UNIQUE (sender_id, client_message_id),

                               CONSTRAINT fk_chat_messages_chat_room
                                   FOREIGN KEY (chat_room_id) REFERENCES chat_rooms (id),

                               CONSTRAINT fk_chat_messages_sender
                                   FOREIGN KEY (sender_id) REFERENCES members (id)
);

CREATE INDEX idx_chat_messages_chat_room_id
    ON chat_messages (chat_room_id);

CREATE INDEX idx_chat_messages_sender_id
    ON chat_messages (sender_id);