-- V7: 거래 테이블의 핀 참조 정합
--  (1) credit_transactions.reference_id(다형 참조) → pin_id(uuid) + pins FK
--  (2) view_transactions(온도 변동 이력) 신규 생성
-- 둘 다 V6(pins.id = uuid) 이후에만 유효하다. bigint → uuid 는 캐스팅 불가하므로
-- credit_transactions 는 데이터를 비우고 타입을 변경한다(개발 단계, 삭제 승인).

-- (1) credit_transactions: reference_id → pin_id(uuid) + pins FK
--     기존 reference_id 는 핀/채팅방/null 등을 가리키던 무결성 미보장 컬럼이었다.
--     핀 참조 전용 pin_id 로 좁히고 pins FK 를 건다. 핀과 무관한 거래는 pin_id = null.
TRUNCATE credit_transactions;

ALTER TABLE credit_transactions RENAME COLUMN reference_id TO pin_id;
ALTER TABLE credit_transactions ALTER COLUMN pin_id TYPE uuid USING (NULL::uuid);  -- nullable 유지
ALTER TABLE credit_transactions ADD CONSTRAINT fk_credit_transactions_pin FOREIGN KEY (pin_id) REFERENCES pins (id);

CREATE INDEX idx_credit_transactions_pin_id ON credit_transactions (pin_id);

-- (2) view_transactions: 온도(view_angle) 변동 이력. type 은 VARCHAR(255)(enum은 자바에서 관리),
--     pin_id 는 nullable uuid FK(핀과 무관한 변동은 null).
CREATE TABLE view_transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT       NOT NULL,
    pin_id        uuid,
    type          VARCHAR(255) NOT NULL,
    change_amount INTEGER      NOT NULL,
    view_after    INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),

    CONSTRAINT fk_view_transactions_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_view_transactions_pin    FOREIGN KEY (pin_id)    REFERENCES pins (id)
);

CREATE INDEX idx_view_transactions_member_id ON view_transactions (member_id);
CREATE INDEX idx_view_transactions_pin_id    ON view_transactions (pin_id);
