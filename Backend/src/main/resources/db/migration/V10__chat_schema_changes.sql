-- V10: 채팅 관련 테이블 스키마 변경
-- 새 ER 설계 반영: chat_rooms 수신자 추가/멱등키 제거, chat_messages 타입 제거,
-- chat_warnings·ai_chat_jobs 신규. 엔티티 매핑과 1:1로 일치시켜 ddl-auto=validate 를 통과시킨다.

-- 1) chat_rooms: recipient_id(수신자=핀 소유자) 추가, idempotency_key 제거
ALTER TABLE chat_rooms ADD COLUMN recipient_id BIGINT;
-- chat_rooms 에 기존 행이 없다는 전제. 기존 행이 있으면 아래로 백필 후 NOT NULL 을 건다.
-- UPDATE chat_rooms cr SET recipient_id = p.member_id FROM pins p WHERE p.id = cr.pin_id;
ALTER TABLE chat_rooms ALTER COLUMN recipient_id SET NOT NULL;
ALTER TABLE chat_rooms ADD CONSTRAINT fk_chat_rooms_recipient
    FOREIGN KEY (recipient_id) REFERENCES members (id);
CREATE INDEX idx_chat_rooms_recipient_id ON chat_rooms (recipient_id);

ALTER TABLE chat_rooms DROP CONSTRAINT uk_chat_rooms_idempotency_key;
ALTER TABLE chat_rooms DROP COLUMN idempotency_key;

-- 2) chat_messages: type 제거 (client_message_id 및 유니크 제약은 유지)
ALTER TABLE chat_messages DROP COLUMN type;

-- 3) chat_warnings: 신규. 채팅방에서 감지된 경고를 기록한다.
CREATE TABLE chat_warnings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_room_id BIGINT      NOT NULL,
    reason_code  VARCHAR(50) NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE,
    updated_at   TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_chat_warnings_chat_room
        FOREIGN KEY (chat_room_id) REFERENCES chat_rooms (id)
);
CREATE INDEX idx_chat_warnings_chat_room_id ON chat_warnings (chat_room_id);

-- 4) ai_chat_jobs: 신규. 특정 채팅방의 메시지 구간(start~end)에 대한 AI 처리 작업 1건을 저장한다.
--    BaseEntity 를 상속하므로 created_at/updated_at 을 모두 두며 JPA auditing 이 채운다(DEFAULT 미사용).
CREATE TABLE ai_chat_jobs (
    request_id       uuid         PRIMARY KEY DEFAULT gen_random_uuid(),
    chat_room_id     BIGINT       NOT NULL,
    start_message_id BIGINT       NOT NULL,
    end_message_id   BIGINT       NOT NULL,
    status           VARCHAR(255) NOT NULL,
    completed_at     TIMESTAMP(6) WITH TIME ZONE,
    created_at       TIMESTAMP(6) WITH TIME ZONE,
    updated_at       TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_ai_chat_jobs_chat_room
        FOREIGN KEY (chat_room_id) REFERENCES chat_rooms (id)
);
-- 채팅방별 작업 이력 조회용
CREATE INDEX idx_ai_chat_jobs_chat_room_id ON ai_chat_jobs (chat_room_id);
-- 특정 status 를 created_at 오래된 순으로 조회하는 용도
CREATE INDEX idx_ai_chat_jobs_status_created_at ON ai_chat_jobs (status, created_at);
