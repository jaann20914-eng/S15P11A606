-- V3: 장소(places)·핀(pins) 스키마
-- Place, Pin 엔티티 매핑과 1:1 로 일치시켜 ddl-auto=validate 를 통과시킨다.
-- 위치 컬럼은 PostGIS GEOGRAPHY(Point,4326) 를 사용한다.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE places (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kakao_place_id VARCHAR(200)          NOT NULL,
    name           VARCHAR(100)          NOT NULL,
    location       geography(Point,4326) NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE,
    updated_at     TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX idx_places_location ON places USING GIST (location);

CREATE TABLE pins (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id          BIGINT                NOT NULL,
    place_id           BIGINT                NOT NULL,
    publisher_status   VARCHAR(255)          NOT NULL,
    video_status       VARCHAR(255)          NOT NULL,
    crowd_level        VARCHAR(255)          NOT NULL,
    capture_location   geography(Point,4326) NOT NULL,
    detail_location    VARCHAR(200),
    memo               VARCHAR(500),
    original_video_key VARCHAR(1024)         NOT NULL,
    blurred_video_key  VARCHAR(1024),
    thumbnail_key      VARCHAR(1024),
    expires_at         TIMESTAMP(6) WITH TIME ZONE,
    created_at         TIMESTAMP(6) WITH TIME ZONE,
    updated_at         TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_pins_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_pins_place FOREIGN KEY (place_id) REFERENCES places (id)
);

CREATE INDEX idx_pins_place_id ON pins (place_id);
CREATE INDEX idx_pins_created_at ON pins (created_at);
CREATE INDEX idx_pins_capture_location ON pins USING GIST (capture_location);
