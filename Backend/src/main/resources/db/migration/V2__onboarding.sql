-- V2: 온보딩 관련 스키마
-- members 온보딩 컬럼 추가 + categories/category_preferences/credit_transactions/onboarding_sessions 생성.
-- 컬럼 타입은 엔티티 매핑(Hibernate 7.2)과 일치시켜 ddl-auto=validate 를 통과시킨다.

ALTER TABLE members
    ADD COLUMN nickname       VARCHAR(20)  NOT NULL,
    ADD COLUMN age_group      VARCHAR(255) NOT NULL,
    ADD COLUMN gender         VARCHAR(255) NOT NULL,
    ADD COLUMN view_angle     INTEGER      NOT NULL DEFAULT 90,
    ADD COLUMN credit_balance INTEGER      NOT NULL DEFAULT 10,
    ADD COLUMN deleted_at     TIMESTAMP(6) WITH TIME ZONE,
    ADD CONSTRAINT uq_member_nickname UNIQUE (nickname),
    ADD CONSTRAINT ck_members_view_angle CHECK (view_angle BETWEEN 90 AND 360),
    ADD CONSTRAINT ck_members_credit_balance CHECK (credit_balance >= 0);

CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    code       VARCHAR(50) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_category_code UNIQUE (code)
);

