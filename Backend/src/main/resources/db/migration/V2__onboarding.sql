CREATE TABLE category_preferences (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT uq_category_preference_member_category UNIQUE (member_id, category_id),
    CONSTRAINT fk_category_preferences_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT fk_category_preferences_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE credit_transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     BIGINT       NOT NULL,
    type          VARCHAR(255) NOT NULL,
    reference_id  BIGINT,
    change_amount INTEGER      NOT NULL,
    balance_after INTEGER      NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_credit_transactions_member FOREIGN KEY (member_id) REFERENCES members (id),
    CONSTRAINT ck_credit_transactions_change_amount CHECK (change_amount <> 0),
    CONSTRAINT ck_credit_transactions_balance_after CHECK (balance_after >= 0)
);

CREATE TABLE onboarding_sessions (
    jti               UUID PRIMARY KEY,
    social_account_id BIGINT NOT NULL,
    expires_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at           TIMESTAMP(6) WITH TIME ZONE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT fk_onboarding_sessions_social_account FOREIGN KEY (social_account_id) REFERENCES social_accounts (id)
);
